"""
export.py -- PINNED. Model + config -> int8 .pte for the lab firmware.

    python3 tools/export.py --config config.json --checkpoint checkpoint.pt \\
                      --out submission/submission.pte

Do not edit this file. The grader re-exports your checkpoint with its own
copy and checks that your .pte has the same structure. What you MAY change
is everything exposed as a command-line flag (add_quant_args below):

  --calib-n N             calibration images (default 512)
  --calib-seed S          which training images (default 0)
  --calib-file F.pt       your own calibration tensor: float [N,3,32,32],
                          normalized like data.normalize() (e.g. a
                          class-balanced or hard-example set)
  --act-observer {histogram,minmax}
                          how activation ranges are chosen (default histogram)
  --weights {per-channel,per-tensor}
                          conv weight scale granularity (default per-channel)
  --fp32-layers L [L ...] leave these layers unquantized (conv0..conv5, fc).
                          They run on portable fp32 kernels: 4x the weight
                          bytes, 4x the activation bytes around them, and
                          much slower. Mostly useful for sensitivity studies.

export.py writes the flags it used to export_flags.json next to the .pte;
submit that file too. The grader re-exports your checkpoint with the same
--weights and --fp32-layers (they change the program's structure) and its
own calibration data (calibration changes values, not structure).

Pipeline (ExecuTorch 1.2 Cortex-M backend, as in quantization_lab/):
    torch.export (channels-last example input)
    -> prepare_pt2e(CortexMQuantizer)   BatchNorm folds into the convs here
    -> calibrate -> convert_pt2e        (the "simulated int8" PyTorch model)
    -> to_edge + CortexMPassManager     conv+ReLU -> cortex_m::quantized_conv2d
                                        (CMSIS-NN), etc.
    -> strip unused constants           see below
    -> to_executorch -> .pte

The model input stays float32 [1,3,32,32]: the firmware normalizes each
frame (data.normalize) and the graph's first op quantizes it.

Stripping: the Cortex-M lowering writes NHWC copies of the weights but
leaves the original NCHW int8 weights (and the per-channel scale/zero-point
tensors) in the program, unused. That would double every .pte. This export
removes them (quantization_lab/'s --strip-unused, always on).
"""

