CL = torch.channels_last
LAYER_NAMES = [f"conv{i}" for i in range(6)] + ["fc"]
# Layer name -> module path inside CifarVGG (for --fp32-layers).
_LAYER_MODULES = {**{f"conv{i}": f"convs.{i}" for i in range(6)}, "fc": "fc"}

PTE_BUDGET_BYTES = 512 * 1024 - 32       # model Flash region minus the header
ARENA_BUDGET_BYTES = 96 * 1024           # firmware ARENA_KB


def example_input():
    """CMSIS-NN works in NHWC, so the export traces a channels-last input."""
    return torch.zeros(1, 3, 32, 32).to(memory_format=CL)


# ------------------------------------------------------------ quantizer ----

STRUCTURAL_FLAGS = ("weights", "fp32_layers")


def add_quant_args(ap: argparse.ArgumentParser) -> argparse.ArgumentParser:
    g = ap.add_argument_group("quantization (the flags you may change)")
    g.add_argument("--calib-n", type=int, default=512)
    g.add_argument("--calib-seed", type=int, default=0)
    g.add_argument("--calib-file", help="float [N,3,32,32] normalized calibration tensor (torch.save)")
    g.add_argument("--act-observer", choices=["histogram", "minmax"], default="histogram")
    g.add_argument("--weights", choices=["per-channel", "per-tensor"], default="per-channel")
    g.add_argument("--fp32-layers", nargs="*", default=[], choices=LAYER_NAMES, metavar="LAYER",
                   help=f"layers to leave in fp32: {' '.join(LAYER_NAMES)}")
    return ap


class _ExcludeModules:
    """Wraps a quantizer NodeFinder, dropping nodes inside given modules."""

    def __init__(self, finder, module_paths):
        self.finder = finder
        filters = [get_module_name_filter(p) for p in module_paths]
        self.excluded = lambda n: any(f(n) for f in filters)

    def find_nodes(self, model):
        return (n for n in self.finder.find_nodes(model) if not self.excluded(n))

    def __repr__(self):
        return f"{self.finder!r} (with exclusions)"


def make_quantizer(args) -> CortexMQuantizer:
    """CortexMQuantizer with the flags applied. Its sub-quantizers are
    [0] convs (per-channel weights), [1] everything else (per-tensor),
    [2] shared-qspec ops (pools, flatten)."""
    q = CortexMQuantizer()
    act = qc.INT8_ACTIVATION_PER_TENSOR_QSPEC
    if args.act_observer == "minmax":
        act = QuantizationSpec(dtype=torch.int8, observer_or_fake_quant_ctr=MinMaxObserver,
                               qscheme=torch.per_tensor_affine)
    if args.weights == "per-channel":
        conv_cfg = qc.CortexMQuantizationConfig(act, act, qc.INT8_WEIGHT_PER_CHANNEL_QSPEC,
                                                qc._get_int32_per_channel_bias_qspec)
    else:
        conv_cfg = qc.CortexMQuantizationConfig(act, act, qc.INT8_WEIGHT_PER_TENSOR_QSPEC,
                                                qc._get_int32_bias_qspec)
    other_cfg = qc.CortexMQuantizationConfig(act, act, qc.INT8_WEIGHT_PER_TENSOR_QSPEC,
                                             qc._get_int32_bias_qspec)
    q.quantizers[0].quantization_config = conv_cfg
    q.quantizers[1].quantization_config = other_cfg
    if args.fp32_layers:
        paths = [_LAYER_MODULES[name] for name in args.fp32_layers]
        # A layer's BatchNorm and ReLU go with it.
        paths += [f"bns.{name[4:]}" for name in args.fp32_layers if name.startswith("conv")]
        for sub in q.quantizers[:2]:
            sub.node_finder = _ExcludeModules(sub.node_finder, paths)
    return q


def calibration_data(args) -> torch.Tensor:
    if args.calib_file:
        x = torch.load(args.calib_file)
        if x.ndim != 4 or tuple(x.shape[1:]) != (3, 32, 32) or not x.is_floating_point():
            raise SystemExit(f"--calib-file must hold a float [N,3,32,32] tensor, got {tuple(x.shape)}")
        return x.float()
    from data import calibration_set
    return calibration_set(args.calib_n, args.calib_seed)


def quantize_model(model: torch.nn.Module, args, calib: torch.Tensor = None, batch: int = 64):
    """PTQ. Returns the convert_pt2e GraphModule: runs in PyTorch (feed it
    channels-last input) and simulates what the board computes."""
    if calib is None:
        calib = calibration_data(args)
    model = copy.deepcopy(model).eval()
    gm = torch.export.export(model, (example_input(),)).module()
    prepared = prepare_pt2e(gm, make_quantizer(args))
    with torch.no_grad():
        for i in range(0, len(calib), batch):
            prepared(calib[i:i + batch].contiguous(memory_format=CL))
    return convert_pt2e(prepared)


# ---------------------------------------------------------------- lower ----

def lower(converted, quantized_fc=True):
    """convert_pt2e graph -> edge program with cortex_m:: ops. aten.linear
    is kept whole only when fc is quantized (the Cortex-M pass needs it to
    form cortex_m::quantized_linear); an fp32 fc must decompose into
    permute_copy + addmm, because the portable library has no linear kernel."""
    ep = torch.export.export(converted, (example_input(),))
    config = EdgeCompileConfig(
        preserve_ops=[torch.ops.aten.linear.default] if quantized_fc else [],
        _check_ir_validity=False,
        _core_aten_ops_exception_list=[torch.ops.aten.max_pool2d.default],
    )
    epm = to_edge(ep, compile_config=config)
    epm._edge_programs["forward"] = CortexMPassManager(epm.exported_program()).transform()
    return epm


def strip_unused_constants(epm):
    """Remove constants the lowered graph no longer reads (see the module
    docstring). Copied from quantization_lab/'s quantize.py."""
    ep = epm.exported_program()
    placeholders = {n.target: n for n in ep.graph_module.graph.nodes if n.op == "placeholder"}
    unused = [s for s in ep.graph_signature.input_specs
              if s.kind in (InputKind.PARAMETER, InputKind.BUFFER, InputKind.CONSTANT_TENSOR)
              and len(placeholders[s.arg.name].users) == 0]
    sig = copy.deepcopy(ep.graph_signature)
    for s in unused:
        sig.input_specs.remove(s)
        if s.target in ep._state_dict:
            del ep._state_dict[s.target]
        elif s.target in ep._constants:
            del ep._constants[s.target]
        ep.graph_module.graph.erase_node(placeholders[s.arg.name])
    ep._graph_signature = sig
    ep.graph_module.recompile()
    return [s.target for s in unused]


def export_pte(model, args, calib=None):
    """Returns (converted GraphModule, ExecutorchProgramManager). The .pte
    bytes are prog.buffer."""
    converted = quantize_model(model, args, calib)
    epm = lower(converted, quantized_fc="fc" not in args.fp32_layers)
    strip_unused_constants(epm)
    prog = epm.to_executorch(config=ExecutorchBackendConfig(extract_delegate_segments=False))
    return converted, prog


# ------------------------------------------------------------- inspect ----
# These read the serialized program, so they work on any .pte file too:
#     plan = load_plan(open("x.pte", "rb").read())

def load_plan(pte_bytes: bytes):
    from executorch.exir._serialize._program import deserialize_pte_binary
    prog = deserialize_pte_binary(pte_bytes)
    prog = getattr(prog, "program", prog)
    return prog.execution_plan[0]


def plan_of(prog_or_bytes):
    if isinstance(prog_or_bytes, (bytes, bytearray)):
        return load_plan(bytes(prog_or_bytes))
    return prog_or_bytes.executorch_program.execution_plan[0]


def planned_bytes(prog_or_bytes) -> int:
    """The memory-planned arena the firmware must provide (index 0 unused)."""
    return int(sum(plan_of(prog_or_bytes).non_const_buffer_sizes))


def program_ops(prog_or_bytes) -> list:
    plan = plan_of(prog_or_bytes)
    return sorted({f"{op.name}.{op.overload}" if op.overload else op.name for op in plan.operators})


def instruction_signature(prog_or_bytes) -> list:
    """[(operator name, [tensor arg shapes...]), ...] in execution order: the
    program's structure, independent of calibration. The grader compares
    this between your .pte and its own re-export of your checkpoint."""
    plan = plan_of(prog_or_bytes)
    sig = []
    for ins in plan.chains[0].instructions:
        a = ins.instr_args
        if not hasattr(a, "op_index"):
            sig.append((type(a).__name__, []))
            continue
        shapes = []
        for vi in a.args:
            v = plan.values[vi].val
            if type(v).__name__ == "Tensor":
                shapes.append(list(v.sizes))
        sig.append((plan.operators[a.op_index].name, shapes))
    return sig


def describe(pte: bytes):
    plan = load_plan(pte)
    n_instr = len(plan.chains[0].instructions)
    ops = program_ops(pte)
    fp32_ops = [o for o in ops if o.startswith("aten::")]
    return {"pte_bytes": len(pte), "planned_bytes": planned_bytes(pte),
            "instructions": n_instr, "ops": ops, "fp32_ops": fp32_ops}


# ------------------------------------------------------------------ CLI ----

def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True, help='{"channels": [...], "num_classes": 10}')
    ap.add_argument("--checkpoint", required=True, help="state_dict for that config")
    ap.add_argument("--out", default=os.path.join(REPO, "submission", "submission.pte"))
    ap.add_argument("--threads", type=int, default=os.cpu_count())
    add_quant_args(ap)
    args = ap.parse_args()
    torch.set_num_threads(args.threads)

    model = load_model(args.config, args.checkpoint)
    with open(args.config) as f:
        print(f"model: {json.load(f)['channels']}")
    flags = {k: v for k, v in vars(args).items()
             if k in ("calib_n", "calib_seed", "calib_file", "act_observer", "weights", "fp32_layers")}
    print(f"quantization flags: {flags}")
    _, prog = export_pte(model, args)
    pte = prog.buffer
    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    with open(args.out, "wb") as f:
        f.write(pte)
    flags_path = os.path.join(os.path.dirname(os.path.abspath(args.out)), "export_flags.json")
    with open(flags_path, "w") as f:
        json.dump(flags, f, indent=1)

    d = describe(pte)
    ok_size = d["pte_bytes"] <= PTE_BUDGET_BYTES
    ok_arena = d["planned_bytes"] <= ARENA_BUDGET_BYTES
    print(f"wrote {args.out} and {flags_path}")
    print(f"  .pte size     {d['pte_bytes']:>9,} bytes  (budget {PTE_BUDGET_BYTES:,})  "
          f"{'OK' if ok_size else 'OVER BUDGET'}")
    print(f"  planned arena {d['planned_bytes']:>9,} bytes  (budget {ARENA_BUDGET_BYTES:,})  "
          f"{'OK' if ok_arena else 'OVER BUDGET'}")
    print(f"  {d['instructions']} instructions; ops: {', '.join(d['ops'])}")
    if d["fp32_ops"]:
        print(f"  note: fp32 (portable) ops present: {', '.join(d['fp32_ops'])}")
    print("Next: python3 tools/check_submission.py")


if __name__ == "__main__":
    main()
